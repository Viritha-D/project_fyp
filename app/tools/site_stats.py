"""
Generate app/site_data.json from retrieval_v2/RESULTS.md. Every number the demo shows about reliability comes from
here; none is typed into the UI code.

Read: automatic evaluation (Overall, seeds 42 and 43), By Category (seed 42), tier reliability (seed 42), the written
development set queries_v2 (a selection set), and the independent test if RESULTS.md has a section headed
"Independent test" (otherwise "pending").

Usage: python app/tools/site_stats.py
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'app' / 'site_data.json'
METRICS = ['hit@1', 'hit@3', 'hit@5', 'recall@5', 'mrr']
STACKED = 'stacked ranker (v2.1/v2.2)'


def section(text, heading):
    m = re.search(r'^(#+) ' + re.escape(heading) + r'.*$', text, re.M)
    if not m:
        return None
    level = len(m.group(1))
    rest = text[m.end():]
    nxt = re.search(r'^#{1,%d} ' % level, rest, re.M)
    return rest[:nxt.start()] if nxt else rest


def metric_rows(block):
    out = {}
    for line in block.splitlines():
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) == 8 and re.match(r'^\d+$', cells[2]):
            vals = {}
            for m, c in zip(METRICS, cells[3:]):
                mm = re.match(r'([\d.]+) \[([\d.]+), ([\d.]+)\]', c)
                vals[m] = {'mean': float(mm.group(1)), 'ci': [float(mm.group(2)), float(mm.group(3))]}
            out[(cells[0], cells[1])] = {'n': int(cells[2]), **vals}
    return out


def tier_rows(block):
    out = {}
    for line in block.splitlines():
        m = re.match(r'\|\s*(low|medium|high)\s*\|\s*(\d+)\s*\|\s*([\d.]+)\s*\|\s*([\d.]+) \[([\d.]+), ([\d.]+)\]', line)
        if m:
            out[m.group(1)] = {'n': int(m.group(2)), 'mean_predicted': float(m.group(3)), 'hit@1': float(m.group(4)),
                               'ci': [float(m.group(5)), float(m.group(6))]}
    return out


def main():
    text = (ROOT / 'retrieval_v2/RESULTS.md').read_text(encoding='utf-8')
    auto = {}
    for seed in (42, 43):
        rows = metric_rows(section(text, f'Overall, seed {seed}'))
        auto[f'seed {seed}'] = {s: rows[('all', s)] for s in ('popularity', 'full_v2', STACKED)}
    cat = metric_rows(section(text, 'By Category (seed 42)'))
    rel = section(text, 'Reliability of the confidence tiers (stacked)')
    tiers42 = tier_rows(rel.split('**Seed 43**')[0])
    dev = metric_rows(section(text, 'Written query set (queries_v2'))
    indep = section(text, 'Independent test')
    data = {
        '_about': 'Generated by app/tools/site_stats.py from retrieval_v2/RESULTS.md. Do not edit by hand.',
        'source_sha256': __import__('hashlib').sha256(text.encode('utf-8')).hexdigest(),
        'system_name': STACKED,
        'automatic_evaluation': {
            'description': 'Five folds by paper, training-only rebuilds, queries from each held-out paper with benchmark '
                           'names masked; two seeds.',
            **auto},
        'by_category_seed42': {c: cat[(c, STACKED)] for c in ('Applied', 'Pure Math')},
        'tiers_seed42': tiers42,
        'dev_written_queries': {
            'description': 'queries_v2: 55 written queries (development set; the v2.2 lambda was selected on it, so these '
                           'are selection numbers, not test numbers).',
            **{s: dev[('all', s)] for s in ('popularity', 'full_v2', STACKED)}},
        'independent_test': {'status': 'pending'} if indep is None else {'status': 'reported', 'markdown': indep.strip()},
    }
    OUT.write_text(json.dumps(data, indent=1) + '\n', encoding='utf-8')
    t = data['tiers_seed42']
    print(f"wrote {OUT.relative_to(ROOT)}: tiers hit@1 low {t['low']['hit@1']} / medium {t['medium']['hit@1']} / high "
          f"{t['high']['hit@1']}; Applied vs Pure Math hit@5 {data['by_category_seed42']['Applied']['hit@5']['mean']} vs "
          f"{data['by_category_seed42']['Pure Math']['hit@5']['mean']}; independent test: {data['independent_test']['status']}")


if __name__ == '__main__':
    sys.exit(main())
